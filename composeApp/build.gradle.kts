// The shared Android library has no BuildConfig, so generate the `.env` values for androidMain.
// Without a `.env` file every value is empty, as before.
val generateAndroidEnvConfig by tasks.registering {
    val envFile = rootProject.file(".env")
    val outputDir = layout.buildDirectory.dir("generated/androidEnvConfig")
    if (envFile.exists()) inputs.file(envFile)
    outputs.dir(outputDir)
    doLast {
        val env = Properties().apply {
            if (envFile.exists()) envFile.inputStream().use { load(it) }
        }
        fun str(key: String, default: String = "") = env.getProperty(key) ?: default
        fun lit(value: String) =
            "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val stringKeys = listOf(
            "API_KEY", "REVENUECAT_ANDROID_KEY", "REVENUECAT_IOS_KEY", "TOTP_SECRET",
            "ANDROID_BANNER_AD_UNIT_ID", "IOS_BANNER_AD_UNIT_ID",
            "ANDROID_INTERSTITIAL_AD_UNIT_ID", "IOS_INTERSTITIAL_AD_UNIT_ID",
            "ANDROID_REWARDED_AD_UNIT_ID", "IOS_REWARDED_AD_UNIT_ID",
            "DATADOG_CLIENT_TOKEN", "DATADOG_APPLICATION_ID", "MAPS_API_KEY",
        )
        val body = buildString {
            stringKeys.forEach { appendLine("    const val $it: String = ${lit(str(it))}") }
            appendLine("    const val DATADOG_ENABLED: Boolean = ${str("DATADOG_ENABLED", "false").lowercase() == "true"}")
            appendLine("    const val DATADOG_ENVIRONMENT: String = ${lit(str("DATADOG_ENVIRONMENT", "production"))}")
        }
        val file = outputDir.get().file("me/calebjones/spacelaunchnow/platform/AndroidEnvConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package me.calebjones.spacelaunchnow.platform\n\n" +
                "// Generated by :composeApp:generateAndroidEnvConfig from .env. Do not edit.\n" +
                "internal object AndroidEnvConfig {\n$body}\n"
        )
    }
}

