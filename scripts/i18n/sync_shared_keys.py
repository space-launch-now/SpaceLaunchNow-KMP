#!/usr/bin/env python3
"""Copy the shared English keys from the Compose master to Wear and the iOS String Catalog.

Spec 017, section 5.3. A key is shared when its name starts with `shared_`. The
Compose master (composeApp/src/commonMain/composeResources/values/strings.xml)
holds the one English text. This script writes each shared key to:

  * wearApp/src/main/res/values/strings.xml  (inside a generated block)
  * iosApp/LaunchWidget/Localizable.xcstrings (the `en` localization only)

Usage:
  python3 scripts/i18n/sync_shared_keys.py          write the two files
  python3 scripts/i18n/sync_shared_keys.py --check  write nothing; exit 1 when a file differs

A second run changes nothing. Text of other keys, and other languages of a
shared key in the catalog, are left as they are. Keep this file ASCII only.
"""
import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

PREFIX = "shared_"
REPO = Path(__file__).resolve().parents[2]
MASTER = REPO / "composeApp/src/commonMain/composeResources/values/strings.xml"
WEAR = REPO / "wearApp/src/main/res/values/strings.xml"
CATALOG = REPO / "iosApp/LaunchWidget/Localizable.xcstrings"

BEGIN = "<!-- BEGIN shared keys: generated by scripts/i18n/sync_shared_keys.py, edit the Compose master -->"
END = "<!-- END shared keys -->"
BLOCK_RE = re.compile(r"[ \t]*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\r?\n?", re.S)

ESCAPES = {"n": "\n", "t": "\t", "'": "'", '"': '"', "\\": "\\", "@": "@", "?": "?"}
ARG_RE = re.compile(r"%(?:(\d+)\$)?([sd])")


def read_master(path):
    """Return a list of (key, comment or None, text) for each shared key, in file order.

    `text` is the parsed XML text: entities decoded, backslash escapes kept.
    """
    parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
    root = ET.parse(path, parser=parser).getroot()
    found, comment = [], None
    for node in root:
        if node.tag is ET.Comment:
            comment = " ".join((node.text or "").split())
            continue
        name = node.get("name", "")
        if name.startswith(PREFIX):
            if node.tag != "string":
                raise SystemExit(f"{path}: shared key {name} is <{node.tag}>; only <string> can be shared")
            if len(node):
                raise SystemExit(f"{path}: shared key {name} holds markup; only plain text can be shared")
            found.append((name, comment, node.text or ""))
        comment = None
    return found


def xml_escape(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def android_value(text):
    """Master text as Android needs it: an apostrophe must be escaped."""
    return re.sub(r"(?<!\\)'", r"\\'", xml_escape(text))


def plain_value(text):
    """Master text with backslash escapes resolved (what the user reads)."""
    out, i = [], 0
    while i < len(text):
        ch = text[i]
        if ch == "\\" and i + 1 < len(text):
            nxt = text[i + 1]
            if nxt == "u" and re.fullmatch(r"[0-9a-fA-F]{4}", text[i + 2:i + 6]):
                out.append(chr(int(text[i + 2:i + 6], 16)))
                i += 6
                continue
            out.append(ESCAPES.get(nxt, nxt))
            i += 2
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def catalog_value(text):
    """Master text as a String Catalog value: `%1$s` becomes `%1$@`; `%1$d` stays."""
    def arg(m):
        pos = f"{m.group(1)}$" if m.group(1) else ""
        return f"%{pos}{'@' if m.group(2) == 's' else 'd'}"
    return ARG_RE.sub(arg, plain_value(text))


def render_wear(current, entries):
    """Return the Wear file text with the generated block holding `entries`."""
    nl = "\r\n" if "\r\n" in current else "\n"
    body = BLOCK_RE.sub("", current)
    if not entries:
        return body
    lines = [f"    {BEGIN}"]
    for key, comment, text in entries:
        if comment:
            lines.append(f"    <!-- {comment} -->")
        lines.append(f'    <string name="{key}">{android_value(text)}</string>')
    lines.append(f"    {END}")
    block = nl.join(lines) + nl
    close = body.rindex("</resources>")
    return body[:close] + block + body[close:]


def render_catalog(current, entries):
    """Return the catalog JSON text with each shared key's `en` value set from `entries`."""
    if not current and not entries:
        return current
    data = json.loads(current) if current else {}
    data.setdefault("sourceLanguage", "en")
    data.setdefault("version", "1.0")
    strings = data.setdefault("strings", {})
    wanted = {key for key, _, _ in entries}
    for key in [k for k in strings if k.startswith(PREFIX) and k not in wanted]:
        del strings[key]
    for key, comment, text in entries:
        item = strings.setdefault(key, {})
        if comment:
            item["comment"] = comment
        else:
            item.pop("comment", None)
        item.setdefault("extractionState", "manual")
        item.setdefault("localizations", {})["en"] = {
            "stringUnit": {"state": "translated", "value": catalog_value(text)}
        }
    data["strings"] = dict(sorted(strings.items()))
    return json.dumps(data, indent=2, ensure_ascii=False, separators=(",", " : ")) + "\n"


def read_text(path):
    return path.read_bytes().decode("utf-8") if path.exists() else ""


def sync(master=MASTER, wear=WEAR, catalog=CATALOG, check=False):
    """Sync both files. Return the paths that differ (check) or changed (write)."""
    entries = read_master(master)
    plans = [
        (wear, render_wear(read_text(wear), entries)),
        (catalog, render_catalog(read_text(catalog), entries)),
    ]
    changed = []
    for path, new in plans:
        if read_text(path) == new:
            continue
        changed.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(new.encode("utf-8"))
    return changed


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when a file differs")
    args = ap.parse_args(argv)
    changed = sync(check=args.check)
    for path in changed:
        print(f"{'differs' if args.check else 'updated'}: {path.relative_to(REPO)}")
    if args.check and changed:
        print("Run: python3 scripts/i18n/sync_shared_keys.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
